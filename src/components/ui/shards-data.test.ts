import { describe, expect, it } from 'vitest'
import { SHARD_VIEWBOX, SHARDS, type ShardPoly, type StripId } from './shards-data'

const pts = (p: ShardPoly) => p.points.split(' ').map((pair) => pair.split(',').map(Number) as [number, number])

/**
 * The generator's depths are tuned for a 390 px phone (scripts/shards.mjs): a thin broken rim that
 * never covers an inscription. The top strip may run deeper because Shards.tsx clips it to the top
 * safe area plus 22 px; the sides stop at 18 px; the bottom strip lives in the bottom safe area.
 */
describe('shards-data (generated by scripts/shards.mjs)', () => {
  it('has 7 across the top, 13 down the left, 15 down the right and 3 at each bottom corner', () => {
    expect(SHARDS.top).toHaveLength(7)
    expect(SHARDS.left).toHaveLength(13)
    expect(SHARDS.right).toHaveLength(15)
    expect(SHARDS.bottom).toHaveLength(6)
  })

  it('every shard has 4 to 6 points, a facet id 0 to 5 and a lit glint run along its inner edge', () => {
    for (const id of Object.keys(SHARDS) as StripId[]) {
      for (const p of SHARDS[id]) {
        const n = pts(p).length
        expect(n).toBeGreaterThanOrEqual(4)
        expect(n).toBeLessThanOrEqual(6)
        expect(p.facet).toBeGreaterThanOrEqual(0)
        expect(p.facet).toBeLessThanOrEqual(5)
        expect(p.glint.length).toBeGreaterThanOrEqual(1)
        for (const g of p.glint) expect(g.split(' ').length).toBeGreaterThanOrEqual(2)
        for (const l of p.lines) expect(l.split(' ')).toHaveLength(2)
      }
    }
  })

  it('side shards never reach past 18 px, the top past 44, the bottom past 16', () => {
    for (const id of ['left', 'right'] as const) {
      for (const p of SHARDS[id]) {
        expect(p.depth).toBeGreaterThanOrEqual(6)
        expect(p.depth).toBeLessThanOrEqual(18)
      }
    }
    for (const p of SHARDS.top) {
      expect(p.depth).toBeGreaterThanOrEqual(10)
      expect(p.depth).toBeLessThanOrEqual(44)
    }
    for (const p of SHARDS.bottom) {
      expect(p.depth).toBeGreaterThanOrEqual(6)
      expect(p.depth).toBeLessThanOrEqual(16)
      expect(p.lines).toHaveLength(0)
    }
  })

  it('the deepest shards sit at the top right and the bottom left', () => {
    const top = SHARDS.top
    expect(top[top.length - 1].depth).toBeGreaterThan(top[0].depth)
    const right = SHARDS.right
    expect(right[0].depth).toBeGreaterThanOrEqual(right[right.length - 1].depth)
    const left = SHARDS.left
    expect(left[left.length - 1].depth).toBeGreaterThanOrEqual(left[0].depth)
    const bl = SHARDS.bottom.slice(0, 3)
    const br = SHARDS.bottom.slice(3)
    expect(Math.max(...bl.map((p) => p.depth))).toBeGreaterThanOrEqual(Math.max(...br.map((p) => p.depth)))
  })

  it('every point stays inside its strip and the outer edge is flush with the screen', () => {
    const box: Record<StripId, [number, number]> = { top: [390, 64], bottom: [390, 64], left: [64, 844], right: [64, 844] }
    for (const id of Object.keys(SHARDS) as StripId[]) {
      expect(SHARD_VIEWBOX[id]).toBe(`0 0 ${box[id][0]} ${box[id][1]}`)
      for (const p of SHARDS[id]) {
        const ps = pts(p)
        for (const [x, y] of ps) {
          expect(x).toBeGreaterThanOrEqual(0)
          expect(x).toBeLessThanOrEqual(box[id][0])
          expect(y).toBeGreaterThanOrEqual(0)
          expect(y).toBeLessThanOrEqual(box[id][1])
        }
        const flush = ps.filter(([x, y]) => (id === 'top' ? y === 0 : id === 'bottom' ? y === 64 : id === 'left' ? x === 0 : x === 64))
        expect(flush.length).toBe(2)
      }
    }
  })

  it('glints only run along edges facing the light (top left): never x-facing on top and bottom, never down-facing on the sides', () => {
    const area = (ps: [number, number][]) => ps.reduce((a, [x0, y0], i) => {
      const [x1, y1] = ps[(i + 1) % ps.length]
      return a + x0 * y1 - x1 * y0
    }, 0)
    for (const id of Object.keys(SHARDS) as StripId[]) {
      for (const p of SHARDS[id]) {
        const poly = pts(p)
        const sign = area(poly) > 0 ? 1 : -1
        for (const g of p.glint) {
          const run = g.split(' ').map((pair) => pair.split(',').map(Number) as [number, number])
          for (let i = 0; i < run.length - 1; i++) {
            const dx = run[i + 1][0] - run[i][0]
            const dy = run[i + 1][1] - run[i][1]
            const nx = sign * dy
            const ny = sign * -dx
            if (id === 'left' || id === 'right') expect(ny).toBeLessThanOrEqual(0.2)
            else expect(nx).toBeLessThanOrEqual(0.2)
          }
        }
      }
    }
  })

  it('shards deeper than 24 px carry 3 or 4 facet lines', () => {
    for (const id of ['top', 'left', 'right'] as const) {
      for (const p of SHARDS[id]) {
        if (p.depth > 24) {
          expect(p.lines.length).toBeGreaterThanOrEqual(3)
          expect(p.lines.length).toBeLessThanOrEqual(4)
        }
      }
    }
  })
})
